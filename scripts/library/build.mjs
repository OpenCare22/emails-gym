import { readFile, writeFile, readdir } from 'node:fs/promises';
import { convertProgram, validateProgram, canApprove, approaches } from '../../frontend/src/lib/library.js';
const root = new URL('../../', import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const source = await read('library/source-UNREVIEWED.json');
const map = await read('library/exercise-map.json');
const corrections = await read('library/corrections.json');
const review = await read('library/review.json');
const files = (await readdir(new URL('catalogue/exercises/', root))).filter(f => f.endsWith('.json')).sort();
const catalogue = Object.fromEntries(await Promise.all(files.map(async f => {
  const e = await read(`catalogue/exercises/${f}`);
  return [e.id, e];
})));
for (const [id, m] of Object.entries(map.exercises)) {
  const definition = source.exercises.find(e => e.id === id);
  Object.assign(m, { equipment: catalogue[m.id]?.equipment, hold: catalogue[m.id]?.hold, unilateral: definition?.unilateral });
}
for (const [key, id] of Object.entries(map.cardio)) {
  if (key !== '_note') map.cardio[key] = { id, equipment: catalogue[id]?.equipment };
}
const programs = source.programs.map(s => {
  const p = convertProgram(s, map, corrections);
  const { errors, blockers } = validateProgram(p, Object.keys(catalogue));
  if (errors.length) throw new Error(`${p.id}:\n${errors.join('\n')}`);
  p.blockers = blockers;
  p.review = review.programs[p.id];
  if (!p.review || !['draft', 'needs_review', 'approved', 'retired'].includes(p.review.status)) throw new Error(`Invalid review status: ${p.id}`);
  if (p.review.status === 'approved' && !canApprove(p, p.review)) throw new Error(`Invalid approval: ${p.id}`);
  return p;
});
const generated = '// generated by scripts/library/build.mjs, do not edit\nexport const programs = ' + JSON.stringify(programs, null, 2) + ';\n';
const target = new URL('frontend/src/lib/library-data.js', root);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== generated) throw new Error('library-data.js is out of date. Run node scripts/library/build.mjs');
} else await writeFile(target, generated);

const cell = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
const table = (head, rows) => [head, head.map(() => '---'), ...rows].map(row => `| ${row.map(cell).join(' | ')} |`).join('\n');
const range = r => r.join(' to ');
const interval = i => `${i.warmup} min warm-up + ${i.rounds} rounds × (${i.hard} min hard at RPE ${i.hardRpe} + ${i.easy} min easy) + ${i.cooldown} min cool-down`;

function reviewSheet() {
  const out = ['<!-- generated by scripts/library/build.mjs --review, do not edit -->', '# Program library: coach review',
    'These seven research programs provide exercise templates and eight weeks of planned sets, repetitions, effort targets and cardio. Friends already use them while the coach reviews them. Every program except a retired one is visible. Until approved, the app shows "Not reviewed by a coach yet". Approval changes the review badge, not access or past workouts. Approval requires your name, date, the exact program version and no open blockers in library/review.json. Record changes in the correction inputs and rebuild before signing off a changed version.',
    'RIR means repetitions in reserve; RPE means rating of perceived exertion. Session tables show baseline lifting prescriptions and week 1 corrected intervals. Weekly rows override sets, RIR and cardio. Timed holds use seconds, not repetitions; their source RIR is retained in the weekly table for review.',
    'Time estimates cover every scheduled session across all eight weeks: 8 minutes of lifting warm-up, 40 seconds per repetition-based work set or the longest hold duration, and rest after each set except the final lifting set, including rest between exercises. Cardio minutes include their own warm-up. Totals round up to 5 minutes. Estimates do not add equipment queues or double unilateral work. Check these assumptions in practice. These are planned targets, not evidence that an individual is ready to progress.',
    'Review exercise choices, order, volume, recovery, effort, time and substitutions. Automated checks are not coaching approval. The research does not experimentally validate these individual programs.'];
  for (const p of programs) {
    const s = source.programs.find(s => s.id === p.id);
    out.push(`\n## ${p.title}`, `Version: ${p.version}. Review state: ${p.review.status}.`,
      `Goal: ${s.goal} (${p.goal}). Level: ${p.level.join(', ')}. ${p.days} days per week for ${p.weeks} weeks.`,
      `Stated time: ${p.statedMinutes} minutes. Estimated session range: ${range(p.minutes)} minutes.`,
      `Equipment: ${p.equipment.join(', ')}.`, `Approach: ${approaches[p.approach]}`, p.notes);
    for (const t of p.templates) {
      out.push(`### ${t.name} (day ${t.day})`, `Warm-up guidance: ${t.warmUp}`, table(['Exercise', 'Sets × reps or seconds / cardio', 'RIR', 'Rest', 'Notes'], t.items.map(i => [
        catalogue[i.ex]?.name || 'Missing mapping', i.mode === 'cardio' ? `${i.min} min ${i.intensity}` : `${i.sets} × ${range(i.sec || i.reps)} ${i.mode === 'time' ? 'seconds' : 'reps'}`,
        i.rir ?? 'Not prescribed', i.rest ? `${i.rest} seconds` : 'Included',
        [i.side ? 'Unilateral.' : '', i.note, i.intervals ? interval(i.intervals) : ''].filter(Boolean).join(' '),
      ])));
    }
    out.push('### Eight-week changes', 'Each sets/RIR list follows the exercise order in the corresponding session table. A dash means no lifting or no cardio.');
    out.push(table(['Week', 'Session', 'Sets by exercise', 'RIR by exercise', 'Cardio', 'Week note'], p.plan.flatMap(w => Object.keys(w.items).map(id => [w.week, p.templates.find(t => t.id === id).name,
      w.items[id].map(i => i.sets).join(', ') || '-', w.items[id].map(i => i.rir).join(', ') || '-',
      w.cardio[id].map(i => `${i.min} min${i.intervals ? `; ${interval(i.intervals)}` : ''}`).join('; ') || '-', w.note]))));
    out.push('### Corrections and original values');
    let corrected = false;
    for (const t of s.templates) {
      const fix = corrections.intervals?.[`${p.id}/${t.id}`];
      if (!fix) continue;
      corrected = true;
      out.push(`**${t.name}:** ${fix.reason}`, `Original template: ${t.cardio[0].minutes} min. ${t.cardio[0].notes}`,
        table(['Week', 'Original scheduled minutes', 'Corrected minutes', 'Corrected segments'], p.plan.map(w => [w.week,
          s.expanded_weeks.find(v => v.week === w.week).sessions.find(v => v.template_id === t.id).cardio[0].minutes,
          w.cardio[t.id][0].min, interval(w.cardio[t.id][0].intervals)])));
    }
    if (!corrected) out.push('No interval corrections applied.');
    if (s.templates.some(t => t.exercises.some(e => e.exercise_id === 'plank'))) out.push('Plank ranges formerly labelled reps are now seconds, with the same numeric range (P0.2).');
    out.push('### Blockers and review warnings', ...(p.blockers.length ? p.blockers.map(b => `- ${b}`) : ['No automated blockers found.']),
      'Warnings for coach review: session time is an estimate; exercise mapping needs confirmation; planned weekly changes do not establish individual readiness.');
    if (s.templates.some(t => t.exercises.some(e => !e.alternatives?.length))) out.push('Source prescriptions have no approved session-specific alternatives (P0.3). Global suggested alternatives have not been imported as approved swaps.');
    out.push('### Exercise mapping used');
    const used = [...new Set(s.templates.flatMap(t => t.exercises.map(e => e.exercise_id)))];
    const modalities = [...new Set(s.templates.flatMap(t => t.cardio.map(c => c.modality)))];
    out.push(table(['Library name / modality', 'Catalogue name', 'Catalogue ID'], [
      ...used.map(id => [source.exercises.find(e => e.id === id)?.name || id, catalogue[map.exercises[id]?.id]?.name || 'Missing mapping', map.exercises[id]?.id]),
      ...modalities.map(m => [m, catalogue[map.cardio[m]?.id]?.name || 'Missing mapping', map.cardio[m]?.id]),
    ]));
    out.push('### Coach sign-off', 'Decision: ☐ Approved   ☐ Approved with changes   ☐ Not approved',
      'Changes required: __________________________________________________________',
      '___________________________________________________________________________',
      'Name: ______________________________   Date: ______________________________',
      `Program/version reviewed: ${p.id} / ${p.version}`, 'Approval with changes remains pending until the changes are applied and checked.');
  }
  return out.join('\n\n') + '\n';
}
if (process.argv.includes('--review')) await writeFile(new URL('docs/emails-gym-planning/COACH_REVIEW.md', root), reviewSheet());
console.log(`Library: ${programs.length} programs, 0 structural errors, ${programs.reduce((n, p) => n + p.blockers.length, 0)} blockers. ${process.argv.includes('--check') ? 'Generated data is current.' : 'Generated data written.'}`);
