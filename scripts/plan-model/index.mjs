// Builds the EG Plan Model's exercise index from catalogue/exercises (JSON only, never media),
// library/exercise-index/core.json and overrides.json, into frontend/src/lib/exercise-index-data.js.
//   node scripts/plan-model/index.mjs           write it and print the counts
//   node scripts/plan-model/index.mjs --check   fail if it is out of date (CI, scripts/fork/check.sh)
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { classify, PATTERNS } from '../../frontend/src/lib/exercise-index.js'

const root = new URL('../../', import.meta.url)
const read = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'))
const check = process.argv.includes('--check')

const { core } = await read('library/exercise-index/core.json')
const { overrides } = await read('library/exercise-index/overrides.json')
const files = (await readdir(new URL('catalogue/exercises/', root))).filter(f => f.endsWith('.json')).sort()
const catalogue = (await Promise.all(files.map(f => read(`catalogue/exercises/${f}`)))).filter(e => e && e.id && e.name)
const ids = new Set(catalogue.map(e => e.id))
for (const id of [...Object.keys(core), ...Object.keys(overrides)]) {
  if (!ids.has(id)) throw new Error(`Exercise index names an exercise the catalogue doesn't have: ${id}`)
}
for (const [id, p] of Object.entries(core)) if (!PATTERNS.includes(p)) throw new Error(`Unknown pattern ${p} for ${id}`)

const INDEX = {}
for (const ex of catalogue) {
  const e = classify(ex, { core, overrides })
  if (e.tier === 'excluded') continue // only what the builder may pick is shipped
  const { id, ...rest } = e
  INDEX[id] = rest
}
const BY_PATTERN = {}
for (const p of PATTERNS) BY_PATTERN[p] = Object.keys(INDEX).filter(id => INDEX[id].pattern === p).sort()

const out = '// generated by scripts/plan-model/index.mjs from catalogue/ and library/exercise-index/, do not edit\n'
  + `export const INDEX = ${JSON.stringify(INDEX)}\n`
  + `export const BY_PATTERN = ${JSON.stringify(BY_PATTERN)}\n`
const target = new URL('frontend/src/lib/exercise-index-data.js', root)

const counts = {}
for (const e of Object.values(INDEX)) {
  const k = `${e.pattern}`
  counts[k] ??= { core: 0, common: 0, variant: 0 }
  counts[k][e.tier]++
}
const total = Object.values(counts).reduce((n, c) => n + c.core + c.common + c.variant, 0)
const summary = `Exercise index: ${total} eligible of ${catalogue.length}; core ${Object.values(counts).reduce((n, c) => n + c.core, 0)}.`

if (check) {
  let current = ''
  try { current = await readFile(target, 'utf8') } catch {}
  if (current !== out) { console.error(summary + ' Generated data is out of date: run node scripts/plan-model/index.mjs'); process.exit(1) }
  console.log(summary + ' Generated data is current.')
} else {
  await writeFile(target, out)
  console.log(summary)
  for (const p of PATTERNS) console.log(`  ${p.padEnd(9)} core ${String(counts[p]?.core || 0).padStart(3)}  common ${String(counts[p]?.common || 0).padStart(4)}  variant ${String(counts[p]?.variant || 0).padStart(4)}`)
}
